#include <cmath>
#include <cstdint>
#include <limits>

namespace nicxlive::core::automation_detail {
inline double sineTan(double x) {
    if (x == 0.0 || std::isnan(x)) return x;
    if (std::isinf(x)) return std::numeric_limits<double>::quiet_NaN();
    const bool sign = std::signbit(x);
    if (sign) x = -x;
    constexpr double pi4 = 0x1.921fb54442d18p-1;
    double y = std::floor(x / pi4);
    double z = y * 0.125;
    z = y - 8.0 * std::floor(z);
    // D's floating-to-int conversion returns int.min for NaN/out-of-range.
    int j = std::isfinite(z) && z >= -2147483648.0 && z < 2147483648.0
        ? static_cast<int>(z) : std::numeric_limits<int>::min();
    if (j & 1) { ++j; y += 1.0; }
    z = ((x - y * 7.853981554508209228515625E-1)
        - y * 7.946627356147928367136046290398E-9)
        - y * 3.061616997868382943065164830688E-17;
    const double zz = z * z;
    if (zz > 1.0e-14) {
        const double p = (-1.3093693918138377764608E4 * zz + 1.1535166483858741613983E6)
            * zz - 1.7956525197648487798769E7;
        const double q = (((zz + 1.3681296347069295467845E4) * zz
            - 1.3208923444021096744731E6) * zz + 2.5008380182335791583922E7)
            * zz - 5.3869575592945462988123E7;
        y = z + z * (zz * p / q);
    } else y = z;
    if (j & 2) y = -1.0 / y;
    return sign ? -y : y;
}
} // namespace nicxlive::core::automation_detail
